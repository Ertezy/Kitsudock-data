// Срок прогона: один на все источники и шаг задач. Время считают монотонные часы
// в миллисекундах; срок — момент на этих же часах (в тестах подставляются свои часы).

/** Причина в журнале и в результате источника, когда он пропущен из-за срока. */
export const OUT_OF_TIME = "вышло время прогона";

/** Часы и срок прогона; без срока время не выходит никогда. */
export interface Timing {
  /** Монотонные часы в миллисекундах; по умолчанию performance.now — он идёт от старта процесса. */
  clock?: () => number;
  /** Момент по часам, с которого новые запросы не начинаются (RUN_BUDGET_MS от старта процесса). */
  deadline?: number;
}

/** Вышел ли срок: часы показывают его (плюс запас `graceMs`) или больше. */
export function timeIsUp({ clock = () => performance.now(), deadline }: Timing, graceMs = 0): boolean {
  return deadline !== undefined && clock() >= deadline + graceMs;
}
